@dataclass
class RobustnessSummary:
    """Aggregated test-set robustness metrics."""

    n_samples: int
    mean_untargeted_radius: float
    median_untargeted_radius: float
    min_untargeted_radius: float
    max_untargeted_radius: float
    certified_accuracy: float
    fragile_samples_count: int               # samples with non-zero radius <= 1
    feature_perturbation_frequency: dict[str, int] = field(default_factory=dict)


@dataclass
class PipelineResult:
    """Complete results generated by the pipeline execution."""

    dataset_name: str
    forest: Forest
    disc: Discretization
    bdd: _bdd.BDD
    compilation_mode: str                     # "unconstrained" or "budgeted"
    budget: int | None
    selector_name: str
    stats: DecompositionStats | None = None
    leaves: list[LeafNode] | None = None
    winning_regions: dict[int, _bdd.Function] | None = None
    sat_counts: dict[int, int] = field(default_factory=dict)
    certified_volumes: dict[int, float] = field(default_factory=dict)
    rankings: dict[str, Any] = field(default_factory=dict)
    sample_robustness: dict[str, Any] | None = None
    test_robustness_df: pd.DataFrame | None = None
    test_robustness_summary: RobustnessSummary | None = None

    def to_dict(self) -> dict[str, Any]:
        """Convert result summary into a JSON-serializable dictionary."""
        out: dict[str, Any] = {
            "dataset_name": self.dataset_name,
            "compilation_mode": self.compilation_mode,
            "budget": self.budget,
            "selector": self.selector_name,
            "n_trees": self.forest.D,
            "n_features": self.forest.n_features,
            "n_classes": self.forest.n_classes,
            "n_input_bits": len(self.disc.all_bit_names),
            "sat_counts": {str(k): v for k, v in self.sat_counts.items()},
            "certified_volumes": {str(k): round(v, 6) for k, v in self.certified_volumes.items()},
        }
        if self.stats:
            out["decomposition_stats"] = asdict(self.stats)
        if self.test_robustness_summary:
            out["test_robustness_summary"] = asdict(self.test_robustness_summary)
        if self.rankings:
            out["rankings"] = {
                k: [(bit, round(val, 5) if isinstance(val, (int, float)) else val) for bit, val, *rest in v[:10]]
                for k, v in self.rankings.items()
            }
        return out


def _run_single_pipeline(
    dataset: str | Forest,
    max_trees: int | None = None,
    budget: int | None = None,
    selector: str | Callable = "modal_variable",
    timeout_seconds: float | None = None,
    max_leaves: int | None = None,
    compute_readouts: bool = True,
    compute_rankings: bool = True,
    evaluate_robustness: bool = True,
    sample: Sequence[float] | np.ndarray | None = None,
    datasets_root: str = "datasets",
    output_dir: str | Path | None = None,
    verbose: bool = True,
) -> PipelineResult:
    """Execute the complete end-to-end RF-to-OBDD verification and robustness pipeline.

    Parameters:
        dataset: Dataset name (e.g. "appendicitis"), path to pkl, or an existing Forest instance.
        max_trees: Prefix k trees to compose (default None = all trees of the forest).
        budget: BDD node budget B (None = unconstrained composition, int = budgeted frontier).
        selector: Split selector strategy name ('modal_variable', 'random_node', 'info_gain',
                  'shapley', 'p_value') or custom callable.
        timeout_seconds: Optional timeout limit for decomposition.
        max_leaves: Optional leaf cutoff limit for decomposition.
        compute_readouts: Whether to compute model counting and continuous certified volume.
        compute_rankings: Whether to compute Information Gain, Shapley, and p-value feature rankings.
        evaluate_robustness: Whether to run MinSwitch robustness on the test set or sample.
        sample: Optional single continuous feature sample to evaluate robustness for.
        datasets_root: Directory containing benchmark datasets.
        output_dir: Folder to save outputs. If None, prints to screen without saving.
        verbose: Whether to print clean progress to console.
    """
    t_start = time.perf_counter()

    # Resolve datasets_root relative to project root if running from a subdirectory (e.g. tests/)
    if not os.path.isabs(datasets_root) and not os.path.exists(datasets_root):
        fallback_root = os.path.join(os.path.dirname(os.path.dirname(__file__)), datasets_root)
        if os.path.exists(fallback_root):
            datasets_root = fallback_root

    # 1. Resolve Forest & Dataset
    dataset_name = "custom_forest"
    dataset_obj: Dataset | None = None

    if isinstance(dataset, str):
        # Could be dataset name or pkl file path
        if os.path.isfile(dataset):
            pkl_path = dataset
            dataset_name = Path(dataset).stem.replace("_rf", "")
        else:
            dataset_name = dataset
            pkl_path = os.path.join(datasets_root, dataset_name, f"{dataset_name}_rf.pkl")

        forest = load_forest(pkl_path, max_trees=max_trees)
        try:
            dataset_obj = load_dataset(dataset_name, root=datasets_root)
        except Exception:
            dataset_obj = None
    else:
        forest = dataset
        dataset_name = getattr(forest, "name", "custom_forest")
        if max_trees is not None and max_trees < forest.D:
            forest = forest.prefix(max_trees)
            forest.name = dataset_name

    # Resolve selector
    if isinstance(selector, str):
        selector_name = selector
        sel_fn = get_selector(selector)
    else:
        selector_name = getattr(selector, "__name__", "custom_selector")
        sel_fn = selector

    if verbose:
        print("=" * 72)
        print(f" PIPELINE EXECUTION: {dataset_name.upper()}")
        print(f" Trees (D): {forest.D} | Features (F): {forest.n_features} | Classes (C): {forest.n_classes}")
        mode_str = f"Budgeted Frontier (B={budget}, selector={selector_name})" if budget is not None else "Unconstrained Composition"
        print(f" Mode: {mode_str}")
        print("=" * 72)

    # 2. Discretization
    disc = discretize(forest)
    n_bits = len(disc.all_bit_names)
    if verbose:
        print(f"[*] Discretization complete: {n_bits} binary input bits across {disc.n_features} features.")

    # 3. Compilation
    bdd: _bdd.BDD
    stats: DecompositionStats | None = None
    leaves: list[LeafNode] | None = None
    win_bdds: dict[int, _bdd.Function] | None = None

    if budget is None:
        compilation_mode = "unconstrained"
        bdd, acc = compose_forest(forest, disc)
        win_bdds = extract_winning_regions(bdd, acc, forest)
        stats = DecompositionStats(
            peak_acc_size=len(acc),
            peak_manager_size=len(bdd),
            num_leaves=1,
            runtime=round(time.perf_counter() - t_start, 4),
            num_splits=0,
            completed=True,
        )
        if verbose:
            print(f"[*] Unconstrained composition finished in {stats.runtime:.3f}s (peak acc size: {stats.peak_acc_size}).")
    else:
        compilation_mode = "budgeted"
        bdd, leaves, stats = budgeted_forest(
            forest,
            disc,
            budget=budget,
            selector=sel_fn,
            return_stats=True,
            timeout_seconds=timeout_seconds,
            max_leaves=max_leaves,
        )
        if stats.completed:
            if compute_readouts:
                win_bdds = extract_frontier_winning_regions(bdd, leaves, forest)
            if verbose:
                print(f"[*] Budgeted decomposition finished: {stats.num_leaves} leaves in {stats.runtime:.3f}s (splits: {stats.num_splits}, peak size: {stats.peak_acc_size}).")
        else:
            if verbose:
                print(f"[!] Budgeted decomposition stopped (limits reached). Completed: False, runtime: {stats.runtime:.3f}s.")

    # 4. Readouts (Deliverable 4)
    sat_counts: dict[int, int] = {}
    certified_volumes: dict[int, float] = {}
    rankings: dict[str, Any] = {}

    if compute_readouts and win_bdds is not None:
        if verbose:
            print("[*] Computing certified model counting & continuous volume...")
        for l in range(forest.n_classes):
            cnt = sat_count(bdd, win_bdds[l], n_bits)
            vol = certified_volume(bdd, win_bdds[l], disc)
            sat_counts[l] = cnt
            certified_volumes[l] = vol
            if verbose:
                print(f"    Class {l}: Models = {cnt:6d} ({cnt / (1 << n_bits):.2%}), Volume = {vol:.4f}")

        if compute_rankings:
            target_class = max(sat_counts, key=sat_counts.get)
            if verbose:
                print(f"[*] Computing feature rankings for dominant Class {target_class}...")
            target_win = win_bdds[target_class]
            rankings["info_gain"] = compute_information_gain_ranking(bdd, target_win, disc)
            rankings["shapley"] = compute_shapley_ranking(bdd, target_win, disc)
            rankings["p_value"] = compute_association_p_value_ranking(bdd, target_win, disc)

    # 5. Robustness Evaluation (Deliverables 4 & 7)
    single_rob_res: dict[str, Any] | None = None
    df_test_rob: pd.DataFrame | None = None
    rob_summary: RobustnessSummary | None = None

    model_rep = leaves if (leaves is not None and len(leaves) > 1 and win_bdds is None) else (win_bdds if win_bdds is not None else leaves)

    # Single sample robustness
    if sample is not None and model_rep is not None:
        single_rob_res = compute_sample_robustness(bdd, model_rep, sample, disc, forest.n_classes)
        if verbose:
            print("[*] Single Sample Robustness:")
            print(f"    Certified Class: {single_rob_res['certified_class']}")
            print(f"    Targeted Radii: {single_rob_res['targeted_radii']}")
            print(f"    Untargeted Radius: {single_rob_res['untargeted_radius']}")
            rival = single_rob_res["nearest_rival"]
            if rival is not None:
                print(f"    Flips to rival {rival}: {single_rob_res['flips_per_label'][rival]}")

    # Test set robustness (Deliverable 7)
    if evaluate_robustness and dataset_obj is not None and model_rep is not None:
        X_test = dataset_obj.X_test
        y_test = dataset_obj.y_test
        n_test = len(X_test)
        if verbose:
            print(f"[*] Evaluating MinSwitch robustness over {n_test} test samples...")

        records = []
        correct_cert_count = 0
        untargeted_list = []
        feature_counts: dict[str, int] = {f"feat_{f}": 0 for f in range(forest.n_features)}

        owner = disc.bit_owner()
        t_rob_start = time.perf_counter()

        for idx in range(n_test):
            x_i = X_test[idx]
            y_i = int(y_test[idx])
            res_i = compute_sample_robustness(bdd, model_rep, x_i, disc, forest.n_classes)

            cert_l = res_i["certified_class"]
            is_correct = (cert_l == y_i)
            if is_correct:
                correct_cert_count += 1

            r_untargeted = res_i["untargeted_radius"]
            untargeted_list.append(r_untargeted)

            rival_l = res_i["nearest_rival"]
            flips = res_i["flips_per_label"].get(rival_l, []) if rival_l is not None else []
            touched = res_i["features_per_label"].get(rival_l, []) if rival_l is not None else []

            for f_idx in touched:
                feature_counts[f"feat_{f_idx}"] += 1

            records.append({
                "sample_idx": idx,
                "true_label": y_i,
                "certified_class": cert_l,
                "correct_certified": is_correct,
                "untargeted_radius": r_untargeted,
                "nearest_rival": rival_l,
                "n_flipped_bits": len(flips),
                "flipped_bits": ";".join(flips),
                "touched_features": ";".join(str(f) for f in touched),
            })

        t_rob_elapsed = time.perf_counter() - t_rob_start
        df_test_rob = pd.DataFrame(records)

        # Summary statistics
        clean_radii = [r for r in untargeted_list if not math.isinf(r)]
        mean_rad = float(np.mean(clean_radii)) if clean_radii else float("inf")
        median_rad = float(np.median(clean_radii)) if clean_radii else float("inf")
        min_rad = float(np.min(clean_radii)) if clean_radii else float("inf")
        max_rad = float(np.max(clean_radii)) if clean_radii else float("inf")
        cert_acc = correct_cert_count / max(1, n_test)
        fragile_count = sum(1 for r in clean_radii if 0.0 < r <= 1.0)

        rob_summary = RobustnessSummary(
            n_samples=n_test,
            mean_untargeted_radius=round(mean_rad, 3),
            median_untargeted_radius=round(median_rad, 3),
            min_untargeted_radius=round(min_rad, 3),
            max_untargeted_radius=round(max_rad, 3),
            certified_accuracy=round(cert_acc, 4),
            fragile_samples_count=fragile_count,
            feature_perturbation_frequency=feature_counts,
        )

        if verbose:
            print(f"[*] Test Set Robustness Complete in {t_rob_elapsed:.2f}s:")
            print(f"    Certified Accuracy: {cert_acc:.2%}")
            print(f"    Mean Untargeted Radius: {mean_rad:.2f} (median: {median_rad:.2f}, range: [{min_rad:.0f}, {max_rad:.0f}])")
            print(f"    Fragile Samples (radius <= 1): {fragile_count}/{n_test}")

    # Build PipelineResult
    result = PipelineResult(
        dataset_name=dataset_name,
        forest=forest,
        disc=disc,
        bdd=bdd,
        compilation_mode=compilation_mode,
        budget=budget,
        selector_name=selector_name,
        stats=stats,
        leaves=leaves,
        winning_regions=win_bdds,
        sat_counts=sat_counts,
        certified_volumes=certified_volumes,
        rankings=rankings,
        sample_robustness=single_rob_res,
        test_robustness_df=df_test_rob,
        test_robustness_summary=rob_summary,
    )

    # 6. Save results to output_dir if specified
    if output_dir is not None:
        out_path = Path(output_dir)
        out_path.mkdir(parents=True, exist_ok=True)

        # 1. Summary JSON
        tag = f"{dataset_name}_k{forest.D}_B{budget if budget is not None else 'inf'}_{selector_name}"
        summary_file = out_path / f"{tag}_summary.json"
        with open(summary_file, "w", encoding="utf-8") as f:
            json.dump(result.to_dict(), f, indent=2)

        # Also save latest default summary
        with open(out_path / f"{dataset_name}_pipeline_summary.json", "w", encoding="utf-8") as f:
            json.dump(result.to_dict(), f, indent=2)

        # 2. Test robustness CSV
        if df_test_rob is not None:
            csv_file = out_path / f"{tag}_test_robustness.csv"
            df_test_rob.to_csv(csv_file, index=False)
            df_test_rob.to_csv(out_path / f"{dataset_name}_test_robustness.csv", index=False)

        if verbose:
            print(f"[+] Results saved to: {out_path.resolve()}")

    if verbose:
        total_time = time.perf_counter() - t_start
        print(f"[*] Total pipeline execution time: {total_time:.2f}s.")
        print("=" * 72)

    return result


def run_pipeline(
    dataset: str | Forest | Sequence[str | Forest] = "appendicitis",
    max_trees: int | Sequence[int] | None = None,
    budget: int | Sequence[int] | None = None,
    selector: str | Callable | Sequence[str | Callable] = "modal_variable",
    timeout_seconds: float | None = None,
    max_leaves: int | None = None,
    compute_readouts: bool = True,
    compute_rankings: bool = True,
    evaluate_robustness: bool = True,
    sample: Sequence[float] | np.ndarray | None = None,
    datasets_root: str = "datasets",
    output_dir: str | Path | None = None,
    verbose: bool = True,
) -> PipelineResult | pd.DataFrame:
    """Execute the RF-to-OBDD verification and robustness pipeline.

    Supports both single-configuration execution (returning PipelineResult)
    and multi-configuration grid execution across datasets, tree prefixes,
    budgets, and selectors (returning pd.DataFrame with formatted console prints).

    Parameters:
        dataset: Dataset name, Forest instance, list of datasets, or "all".
        max_trees: Tree prefix count, list of tree prefixes (e.g. [3, 5, 7, 10]), or None (full forest).
        budget: BDD budget B, list of budgets (e.g. [50, 100, 200, 500]), or None (unconstrained).
        selector: Selector name ('modal_variable', 'info_gain', etc.), list of selectors, or 'all'.
        timeout_seconds: Optional timeout per decomposition.
        max_leaves: Optional leaf cutoff limit per decomposition.
        compute_readouts: Whether to compute model counting and continuous volume.
        compute_rankings: Whether to compute feature rankings.
        evaluate_robustness: Whether to evaluate MinSwitch test-set robustness.
        sample: Optional continuous feature sample for individual robustness evaluation.
        datasets_root: Root directory of benchmark datasets.
        output_dir: Directory to save results. If None, results are printed to console without saving to disk.
        verbose: Verbosity level for console output.
    """
    # Resolve datasets_root relative to project root if running from a subdirectory (e.g. tests/)
    if not os.path.isabs(datasets_root) and not os.path.exists(datasets_root):
        fallback_root = os.path.join(os.path.dirname(os.path.dirname(__file__)), datasets_root)
        if os.path.exists(fallback_root):
            datasets_root = fallback_root

    # 1. Resolve dataset list
    if isinstance(dataset, str) and dataset.lower() == "all":
        datasets_root_path = Path(datasets_root)
        if datasets_root_path.exists():
            dataset_list = sorted([
                p.name for p in datasets_root_path.iterdir()
                if p.is_dir() and (p / f"{p.name}_rf.pkl").exists()
            ])
        else:
            dataset_list = ["appendicitis"]
    elif isinstance(dataset, (list, tuple)):
        dataset_list = list(dataset)
    else:
        dataset_list = [dataset]

    # 2. Resolve tree list
    if isinstance(max_trees, (list, tuple, range)):
        trees_list = list(max_trees)
    else:
        trees_list = [max_trees]

    # 3. Resolve budget list
    if isinstance(budget, (list, tuple, range)):
        budgets_list = list(budget)
    else:
        budgets_list = [budget]

    # 4. Resolve selector list
    if isinstance(selector, str) and selector.lower() == "all":
        selectors_list = list(SELECTORS.keys())
    elif isinstance(selector, (list, tuple)):
        selectors_list = list(selector)
    else:
        selectors_list = [selector]

    # Check whether this is a single execution or a grid execution
    is_grid = (
        len(dataset_list) > 1
        or len(trees_list) > 1
        or len(budgets_list) > 1
        or len(selectors_list) > 1
    )

    if not is_grid:
        return _run_single_pipeline(
            dataset=dataset_list[0],
            max_trees=trees_list[0],
            budget=budgets_list[0],
            selector=selectors_list[0],
            timeout_seconds=timeout_seconds,
            max_leaves=max_leaves,
            compute_readouts=compute_readouts,
            compute_rankings=compute_rankings,
            evaluate_robustness=evaluate_robustness,
            sample=sample,
            datasets_root=datasets_root,
            output_dir=output_dir,
            verbose=verbose,
        )

    # Grid execution
    total_runs = len(dataset_list) * len(trees_list) * len(budgets_list) * len(selectors_list)
    print("=" * 80)
    print(f" LAUNCHING GRID PIPELINE: {total_runs} runs")
    print(f" Datasets ({len(dataset_list)}): {dataset_list if len(dataset_list) <= 6 else f'{len(dataset_list)} datasets'}")
    print(f" Trees: {trees_list} | Budgets: {budgets_list}")
    print(f" Selectors: {[s if isinstance(s, str) else getattr(s, '__name__', 'custom') for s in selectors_list]}")
    if output_dir:
        print(f" Output folder: {output_dir}")
    else:
        print(" Output mode: Screen only (no disk persistence)")
    print("=" * 80)

    rows = []
    run_idx = 0
    t_grid_start = time.perf_counter()

    for ds in dataset_list:
        for k in trees_list:
            for b in budgets_list:
                for sel in selectors_list:
                    run_idx += 1
                    sel_name = sel if isinstance(sel, str) else getattr(sel, "__name__", "custom")
                    ds_name = ds if isinstance(ds, str) else getattr(ds, "name", "custom")
                    if verbose and total_runs > 10 and run_idx % 5 == 1:
                        print(f"[{run_idx}/{total_runs}] Running {ds_name} (k={k}, B={b}, selector={sel_name})...")

                    res = _run_single_pipeline(
                        dataset=ds,
                        max_trees=k,
                        budget=b,
                        selector=sel,
                        timeout_seconds=timeout_seconds,
                        max_leaves=max_leaves,
                        compute_readouts=compute_readouts,
                        compute_rankings=compute_rankings,
                        evaluate_robustness=evaluate_robustness,
                        datasets_root=datasets_root,
                        output_dir=output_dir,
                        verbose=False,
                    )

                    row = {
                        "Dataset": res.dataset_name,
                        "Trees (k)": res.forest.D,
                        "Budget (B)": res.budget if res.budget is not None else "inf",
                        "Selector": res.selector_name,
                        "Peak Acc Size": res.stats.peak_acc_size if res.stats else 0,
                        "Leaves": res.stats.num_leaves if res.stats else 0,
                        "Splits": res.stats.num_splits if res.stats else 0,
                        "Runtime (s)": round(res.stats.runtime, 4) if res.stats else 0.0,
                        "Completed": res.stats.completed if res.stats else False,
                    }
                    if evaluate_robustness and res.test_robustness_summary:
                        row["Cert Acc"] = f"{res.test_robustness_summary.certified_accuracy:.1%}"
                        row["Mean Radius"] = res.test_robustness_summary.mean_untargeted_radius
                        row["Fragile"] = res.test_robustness_summary.fragile_samples_count
                    rows.append(row)

    grid_elapsed = time.perf_counter() - t_grid_start
    df = pd.DataFrame(rows)

    print("\n" + "=" * 80)
    print(" GRID PIPELINE EXECUTION SUMMARY")
    print("=" * 80)
    display_cols = ["Dataset", "Trees (k)", "Budget (B)", "Selector", "Peak Acc Size", "Leaves", "Runtime (s)", "Completed"]
    if "Cert Acc" in df.columns:
        display_cols.extend(["Cert Acc", "Mean Radius", "Fragile"])
    print(df[display_cols].to_string(index=False))
    print("=" * 80)

    # Selector performance comparison
    if len(selectors_list) > 1:
        print("\n=== Selector Aggregated Performance ===")
        sel_agg = df.groupby("Selector").agg({
            "Leaves": ["mean", "max"],
            "Runtime (s)": ["mean", "sum"],
            "Completed": "all",
        }).round(3)
        print(sel_agg)
        print("=" * 80)

    print(f"\n[*] Grid execution completed in {grid_elapsed:.2f}s across {total_runs} configurations.\n")

    if output_dir is not None:
        out_p = Path(output_dir)
        out_p.mkdir(parents=True, exist_ok=True)
        csv_file = out_p / "grid_pipeline_summary.csv"
        df.to_csv(csv_file, index=False)
        print(f"[+] Grid summary table saved to {csv_file}")

    return df


def find_scaling_wall(
    dataset: str | Forest,
    budget: int = 200,
    selector: str | Callable = "modal_variable",
    candidate_trees: Sequence[int] | None = None,
    timeout_seconds: float = 5.0,
    max_leaves: int = 500,
    datasets_root: str = "datasets",
    verbose: bool = False,
) -> dict[str, Any]:
    """Find the scaling wall k_max for a model where full forest does not complete.

    As required by Section 14 Deliverable 6:
    When a forest is too large to finish under any budget, the encoding is to be limited
    to its first k trees, the prefix T0, ..., Tk-1, and k is increased as far as completion
    allows, so that the scaling wall is located per model rather than merely recorded as a failure.

    Parameters:
        dataset: Dataset name or Forest instance.
        budget: BDD node budget B (default: 200).
        selector: Split selector strategy (default: 'modal_variable').
        candidate_trees: Optional explicit list of k values to test.
        timeout_seconds: Timeout per k-run in seconds (default: 5.0).
        max_leaves: Max leaf threshold per k-run (default: 500).
        datasets_root: Path to datasets folder.
        verbose: Whether to print progress to console.

    Returns:
        dict containing dataset metadata, k_max, completion status, and evaluation history.
    """
    # Resolve datasets_root
    if not os.path.isabs(datasets_root) and not os.path.exists(datasets_root):
        fallback_root = os.path.join(os.path.dirname(os.path.dirname(__file__)), datasets_root)
        if os.path.exists(fallback_root):
            datasets_root = fallback_root

    # Resolve forest
    if isinstance(dataset, str):
        if os.path.isfile(dataset):
            pkl_path = dataset
            ds_name = Path(dataset).stem.replace("_rf", "")
        else:
            ds_name = dataset
            pkl_path = os.path.join(datasets_root, ds_name, f"{ds_name}_rf.pkl")
        forest = load_forest(pkl_path)
    else:
        forest = dataset
        ds_name = getattr(forest, "name", "custom_forest")

    total_D = forest.D

    if candidate_trees is None:
        default_steps = [3, 5, 7, 10, 15, 20, 25, 30, 40, 50, 60, 75, 100]
        candidates = [k for k in default_steps if k < total_D]
        if total_D not in candidates:
            candidates.append(total_D)
    else:
        candidates = sorted(list(candidate_trees))

    k_max = None
    best_stats = None
    history = []

    if verbose:
        print(f"[*] Locating scaling wall for '{ds_name}' (Total D={total_D}, B={budget}, selector={selector})...")

    for k in candidates:
        if k > total_D:
            continue
        res = _run_single_pipeline(
            dataset=forest,
            max_trees=k,
            budget=budget,
            selector=selector,
            timeout_seconds=timeout_seconds,
            max_leaves=max_leaves,
            compute_readouts=False,
            compute_rankings=False,
            evaluate_robustness=False,
            datasets_root=datasets_root,
            verbose=False,
        )
        st = res.stats
        completed = st.completed if st else False
        history.append({
            "k": k,
            "completed": completed,
            "peak_acc_size": st.peak_acc_size if st else 0,
            "num_leaves": st.num_leaves if st else 0,
            "runtime": round(st.runtime, 4) if st else 0.0,
            "num_splits": st.num_splits if st else 0,
        })
        if completed:
            k_max = k
            best_stats = st
            if verbose:
                print(f"    k={k:3d} -> COMPLETED (leaves={st.num_leaves:4d}, peak={st.peak_acc_size:4d}, time={st.runtime:.2f}s)")
        else:
            if verbose:
                print(f"    k={k:3d} -> HIT WALL (stopped after {st.runtime:.2f}s, leaves={st.num_leaves:4d})")
            break

    return {
        "dataset_name": ds_name,
        "total_trees": total_D,
        "k_max": k_max,
        "completed_full": (k_max == total_D),
        "scaling_wall_hit": (k_max is not None and k_max < total_D) or (k_max is None),
        "best_stats": best_stats,
        "history": history,
    }




